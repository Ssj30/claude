// Writes the app's public URL into the thank-you extension, which can't read
// environment variables. Runs before `npm run deploy`.
import { readFileSync, writeFileSync } from "node:fs";

let url = process.env.SHOPIFY_APP_URL;
if (!url) {
  const toml = readFileSync(new URL("../shopify.app.toml", import.meta.url), "utf8");
  url = /^application_url\s*=\s*"([^"]+)"/m.exec(toml)?.[1];
}
if (!url || url.includes("example.com")) {
  console.error("Set SHOPIFY_APP_URL (or application_url in shopify.app.toml) to the app's public https URL first.");
  process.exit(1);
}
url = url.replace(/\/+$/, "");
writeFileSync(
  new URL("../extensions/thank-you-reward/src/config.js", import.meta.url),
  `// Generated by scripts/write-extension-config.mjs. Do not edit.\nexport const APP_URL = ${JSON.stringify(url)};\n`,
);
console.log(`Thank-you extension will call ${url}`);
